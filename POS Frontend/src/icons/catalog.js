export function iconForAction(label, fallback = 'save') {
  if (typeof label !== 'string') return fallback;
  const actions = [
    [/\b(sign out|log out)\b/i, 'logout'], [/\b(sign in|log in)\b/i, 'login'],
    [/\b(delete|remove)\b/i, 'delete'], [/\b(cancel|close|dismiss)\b/i, 'close'],
    [/\b(previous|prev)\b/i, 'previous'], [/\bnext\b/i, 'next'],
    [/\b(search|find)\b/i, 'search'], [/\b(edit|update)\b/i, 'edit'],
    [/\b(export|download)\b/i, 'download'], [/\b(import|upload)\b/i, 'upload'],
    [/\b(refresh|retry|try again|reconcile)\b/i, 'refresh'], [/\bprint\b/i, 'print'],
    [/\b(approve|confirm|activate|mark|resolve)\b/i, 'check'],
    [/\brefund\b/i, 'refund'], [/\b(return|exchange)\b/i, 'returns'],
    [/\b(release|unreserve)\b/i, 'release'], [/\breserv/i, 'reserve'],
    [/\bquote\b/i, 'quote'], [/\barchive\b/i, 'inventory'],
    [/\b(add|new|create)\b/i, 'add'], [/\b(post|complete|submit|send)\b/i, 'post'],
    [/\b(payment|checkout|stripe|subscription|billing)\b/i, 'billing'],
    [/\b(report|summary)\b/i, 'reports'], [/\bsettings\b/i, 'settings'],
    [/\b(support|help)\b/i, 'support'], [/\balert/i, 'alerts'],
    [/\baudit\b/i, 'audit'], [/\b(stock|balance|adjustment|count)\b/i, 'inventory'],
    [/\b(sale|receipt)\b/i, 'sales'], [/\b(order|purchase|supplier)\b/i, 'purchasing'],
    [/\bexpense/i, 'expense'], [/\b(customer|member|role|access)\b/i, 'team'],
    [/\b(open|view|review|details|preview)\b/i, 'view'], [/\bsave\b/i, 'save'],
  ];
  return actions.find(([pattern]) => pattern.test(label))?.[1] || fallback;
}
